def handles(state):
    """Each point's (in, out) handle, from its segments' lengths and angles."""
    pts, segs = state["pts"], state["segs"]
    n = len(pts)
    h = [[None, None] for _ in range(n)]
    for i, (l0, a0, l1, a1) in enumerate(segs):
        a, b = pts[i], pts[(i + 1) % n]
        h[i][1] = (a[0] + l0 * math.cos(math.radians(a0)), a[1] + l0 * math.sin(math.radians(a0)))
        h[(i + 1) % n][0] = (b[0] - l1 * math.cos(math.radians(a1)), b[1] - l1 * math.sin(math.radians(a1)))
    return h


def pose(layer, state):
    for i, p in enumerate(state["pts"]):
        layer.set_point(i, to_layer(p))
    for i, (h_in, h_out) in enumerate(handles(state)):
        for side, h in (("IN", h_in), ("OUT", h_out)):
            if h is not None:
                layer.place_handle(0, i, side, to_layer(h), keep_other=True)
    for i, (h_in, h_out) in enumerate(handles(state)):
        _, got_in, got_out = layer.curve_handles(0)[i]
        for h, got in ((h_in, got_in), (h_out, got_out)):
            assert h is None or math.dist(to_layer(h), got) < 1e-5, ("the handle is where Harmony's is", i, h, got)


def new_layer(name):
    ops.layer.new()
    layer = layers.active
    layer.name = name
    return layer


worst = 0.0
for n, case in enumerate(CASES):
    what = "%s %s (%d)" % ("closed" if case["closed"] else "open", case["kind"], n)
    ops.wm.read_homefile(confirmed="1")
    doc.frame_current = 0
    cage = new_layer("Envelope")
    cage.add_curve([to_layer(p) for p in case["rest"]["pts"]], closed=case["closed"])
    pose(cage, case["rest"])
    art = new_layer("Art")
    art.add_curve([to_layer(q[:2]) for q in case["points"]])
    assert ops.object.modifier_add(type="ENVELOPE_DEFORM") == {'FINISHED'}
    art.modifier_set(0, layer="Envelope", shape=cage.shapes[0][0], precision=0.0)
    got = art.evaluated()[0]
    assert all(math.dist(g, to_layer(q[:2])) < 1e-6 for g, q in zip(got, case["points"])), (what, "at rest")
    doc.frame_current = 8
    pose(cage, case["now"])
    doc.frame_current = 9
    doc.frame_current = 8
    got = art.evaluated()[0]
    assert len(got) == len(case["points"]), (what, len(got))
    for (x, y, hx, hy), g in zip(case["points"], got):
        f = to_field(g)
        error = math.hypot((f[0] - hx) * AX, f[1] - hy)
        worst = max(worst, error)
        assert error < 0.001, (what, "as Harmony puts it", (x, y), (hx, hy), f, round(error, 5))

