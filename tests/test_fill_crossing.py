"""An outline crossing itself fills as it is, not up to a straight line between its ends: two lines of a thin shape bent
across each other (a mouth's closed lip line under a mesh) filled a wedge as big as the mouth, flickering as they crossed.
A background run draws nothing, so this reads the area the fill's triangles cover (oanim.wm.fill_covers).

Run with:  OpenAnimate --background --python tests/test_fill_crossing.py
"""

import oanim

covers = oanim.wm.fill_covers


def close(a, b, eps=1e-3):
    return abs(a - b) < eps


# Outlines that don't cross fill as ever.
assert close(covers([(0, 0), (2, 0), (2, 2), (0, 2)]), 4.0)
assert close(covers([(0, 2), (2, 2), (2, 0), (0, 0)]), 4.0), "either way round"
assert close(covers([(0, 0), (2, 0), (2, 1), (1, 1), (1, 2), (0, 2)]), 3.0), "with a notch in it"
assert close(covers([(0, 0), (1, 0), (2, 0)]), 0.0), "with no area"

# A figure of eight: both its loops, nothing else.
assert close(covers([(0, 0), (2, 2), (2, 0), (0, 2)]), 2.0), covers([(0, 0), (2, 2), (2, 0), (0, 2)])

