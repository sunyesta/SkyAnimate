def straight_handles(points, closed):
    """Each point's (in, out) handle, a third of the way along its sides, as Harmony's Envelope Creator makes them."""
    n = len(points)
    r = []
    for i, p in enumerate(points):
        prev = points[i - 1] if closed or i > 0 else None
        nxt = points[(i + 1) % n] if closed or i + 1 < n else None
        h_in = (p[0] + (prev[0] - p[0]) / 3, p[1] + (prev[1] - p[1]) / 3) if prev else None
        h_out = (p[0] + (nxt[0] - p[0]) / 3, p[1] + (nxt[1] - p[1]) / 3) if nxt else None
        r.append((h_in, h_out))
    return r


def new_layer(name):
    ops.layer.new()
    layer = layers.active
    layer.name = name
    return layer


def pose(layer, points, handles):
    for i, p in enumerate(points):
        layer.set_point(i, to_layer(p))
    for i, (h_in, h_out) in enumerate(handles):
        for side, h in (("IN", h_in), ("OUT", h_out)):
            if h is not None:
                layer.place_handle(0, i, side, to_layer(h), keep_other=True)
    for i, (h_in, h_out) in enumerate(handles):
        _, got_in, got_out = layer.curve_handles(0)[i]
        for h, got in ((h_in, got_in), (h_out, got_out)):
            assert h is None or math.dist(to_layer(h), got) < 1e-6, ("the handle is where Harmony's is", i, h, got)


def envelope(name, points, closed):
    layer = new_layer(name)
    layer.add_curve([to_layer(p) for p in points], closed=closed)
    pose(layer, points, straight_handles(points, closed))
    return layer


def bent_by(cage, name, cases):
    art = new_layer(name)
    art.add_curve([to_layer(c[:2]) for c in cases])
    assert ops.object.modifier_add(type="ENVELOPE_DEFORM") == {'FINISHED'}
    art.modifier_set(0, layer=cage.name, shape=cage.shapes[0][0], precision=0.0)
    m = art.modifiers[0]
    assert m["type"] in ("CAGE_DEFORM", "CURVE_DEFORM") and m["kind"] == "Envelope", m
    return art


def check(art, cases, what):
    got = art.evaluated()[0]
    assert len(got) == len(cases), (what, len(got), len(cases))
    errors = []
    for (x, y, hx, hy, far), q in zip(cases, got):
        f = to_field(q)
        error = math.hypot(f[0] - hx, f[1] - hy)
        errors.append(error)
        assert error < 0.004 + 0.015 * far, (what, "as Harmony puts it", (x, y), (hx, hy), f, round(error, 4))
    assert statistics.median(errors) < 0.003, (what, statistics.median(errors))
    return errors


