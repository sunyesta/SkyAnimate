# A small shape of many segments (an eye's warp, resampled: 44 points, 0.06 across, its pieces about a thousandth
# apart) bends just as the same rig 25 times the size, scaled: Weighted has no size of its own (with Pre-Blend 0).
# Harmony keeps every two places at least 0.01 apart in its solve, which on a shape this small flattens most of it.
def small_and_large(scale):
    r, c, n = 0.06 * scale, (0.1 * scale, 0.5 * scale), 44
    ring = [(c[0] + r * math.cos(2 * math.pi * i / n), c[1] + r * math.sin(2 * math.pi * i / n)) for i in range(n)]
    shape = new_layer("Eye warp %g" % scale)
    shape.add_curve(ring, closed=True)
    inside = [(c[0] + f * r * math.cos(2 * math.pi * i / 24 + 0.1), c[1] + f * r * math.sin(2 * math.pi * i / 24 + 0.1))
              for f in (0.95, 0.6, 0.2) for i in range(24)]
    art = new_layer("Eye %g" % scale)
    art.add_curve(inside)
    assert ops.object.modifier_add(type="ENVELOPE_DEFORM") == {'FINISHED'}
    art.modifier_set(0, layer=shape.name, shape=shape.shapes[0][0], precision=0.0, envelope_method="WEIGHTED")
    return shape, ring, art, inside


