def new_layer(name):
    ops.layer.new()
    layer = layers.active
    layer.name = name
    return layer


def pose(layer, points, handles):
    for i, p in enumerate(points):
        layer.set_point(i, to_layer(p))
    for i, (h_in, h_out) in enumerate(handles):
        for side, h in (("IN", h_in), ("OUT", h_out)):
            if h is not None:
                layer.place_handle(0, i, side, to_layer(h), keep_other=True)


def straight_handles(points, closed):
    n = len(points)
    r = []
    for i, p in enumerate(points):
        prev = points[i - 1] if closed or i > 0 else None
        nxt = points[(i + 1) % n] if closed or i + 1 < n else None
        h_in = (p[0] + (prev[0] - p[0]) / 3, p[1] + (prev[1] - p[1]) / 3) if prev else None
        h_out = (p[0] + (nxt[0] - p[0]) / 3, p[1] + (nxt[1] - p[1]) / 3) if nxt else None
        r.append((h_in, h_out))
    return r


def envelope(name, points, closed):
    layer = new_layer(name)
    layer.add_curve([to_layer(p) for p in points], closed=closed)
    pose(layer, points, straight_handles(points, closed))
    return layer


def bent_by(shape, name, cases, **settings):
    art = new_layer(name)
    art.add_curve([to_layer(c[:2]) for c in cases])
    assert ops.object.modifier_add(type="ENVELOPE_DEFORM") == {'FINISHED'}
    art.modifier_set(0, layer=shape.name, shape=shape.shapes[0][0], precision=0.0, envelope_method="WEIGHTED",
                     **settings)
    m = art.modifiers[0]
    assert m["envelope_method"] == "WEIGHTED" and m["kind"] == "Envelope", m
    for key, value in settings.items():
        assert abs(m[key] - value) < 1e-6, (key, m[key])
    return art


def errors(art, cases):
    got = art.evaluated()[0]
    assert len(got) == len(cases), (len(got), len(cases))
    return [math.hypot(to_field(q)[0] - hx, to_field(q)[1] - hy) for (x, y, hx, hy), q in zip(cases, got)]


def check(art, cases, what):
    e = errors(art, cases)
    worst = max(range(len(e)), key=lambda i: e[i])
    assert e[worst] < 0.03, (what, "as Harmony puts it", cases[worst], round(e[worst], 4))
    assert statistics.median(e) < 0.01, (what, statistics.median(e))
    # The Standard method (Harmony's envelope deformer) is something else: the test tells them apart.
    art.modifier_set(0, envelope_method="STANDARD")
    standard = statistics.median(errors(art, cases))
    art.modifier_set(0, envelope_method="WEIGHTED")
    assert standard > 0.05, (what, "Standard is not Weighted", standard)
    print(what, "median %.4f, worst %.4f (Standard %.3f)" % (statistics.median(e), e[worst], standard))


